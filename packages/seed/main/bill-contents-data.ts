export function createBillContents(
  insertedBills: { id: string; name: string }[]
) {
  const results = [];
  for (const content of billContentsWithBillName) {
    const bill = insertedBills.find((b) => b.name === content.bill_name);
    if (!bill) {
      console.warn(`  ⚠️  Bill content skipped (no matching bill): ${content.bill_name}`);
      continue;
    }
    results.push({
      bill_id: bill.id,
      difficulty_level: content.difficulty_level,
      title: content.title,
      summary: content.summary,
      content: content.content,
    });
  }
  return results;
}
